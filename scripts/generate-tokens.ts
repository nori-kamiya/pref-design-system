import { writeFileSync, readFileSync, mkdirSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, resolve } from 'node:path'
import { buildPrefectureTheme, auditTheme, type PrefectureTokens } from '../src/lib/colorEngine'

const __dirname = dirname(fileURLToPath(import.meta.url))
const root = resolve(__dirname, '..')

interface PrefectureSource {
  id: string
  nameJa: string
  nameEn: string
  region: string
  hex: string
  rationale: string
}

const sources: PrefectureSource[] = JSON.parse(
  readFileSync(resolve(root, 'src/tokens/prefectures.json'), 'utf-8'),
)

function cssBlock(id: string, tokens: PrefectureTokens): string {
  return [
    `  --pref-identity: ${tokens.identity};`,
    `  --pref-primary: ${tokens.primary};`,
    `  --pref-on-primary: ${tokens.onPrimary};`,
    `  --pref-primary-strong: ${tokens.primaryStrong};`,
    `  --pref-tint-bg: ${tokens.tintBg};`,
    `  --pref-tint-border: ${tokens.tintBorder};`,
    `  --pref-surface: ${tokens.surface};`,
    `  --pref-surface-alt: ${tokens.surfaceAlt};`,
    `  --pref-text: ${tokens.text};`,
    `  --pref-text-muted: ${tokens.textMuted};`,
    `  --pref-border: ${tokens.border};`,
  ].join('\n')
}

const cssParts: string[] = [
  '/* AUTO-GENERATED by scripts/generate-tokens.ts — do not edit by hand. */',
  '',
]

const allAudits: ReturnType<typeof auditTheme> = []
const generatedData: Array<PrefectureSource & { light: PrefectureTokens; dark: PrefectureTokens }> = []

for (const src of sources) {
  const theme = buildPrefectureTheme(src.hex)
  allAudits.push(...auditTheme(src.id, theme))
  generatedData.push({ ...src, light: theme.light, dark: theme.dark })

  cssParts.push(`[data-pref='${src.id}'] {`, cssBlock(src.id, theme.light), '}')
  cssParts.push(
    `@media (prefers-color-scheme: dark) {`,
    `  [data-pref='${src.id}']:not([data-theme='light']) {`,
    cssBlock(src.id, theme.dark)
      .split('\n')
      .map((l) => '  ' + l)
      .join('\n'),
    '  }',
    '}',
  )
  cssParts.push(`[data-pref='${src.id}'][data-theme='dark'] {`, cssBlock(src.id, theme.dark), '}')
  cssParts.push('')
}

// Default root scope so the app has tokens before a prefecture is chosen.
cssParts.unshift(
  `:root {`,
  cssBlock('default', buildPrefectureTheme(sources[0].hex).light),
  `}`,
  '',
)

mkdirSync(resolve(root, 'src/styles'), { recursive: true })
writeFileSync(resolve(root, 'src/styles/tokens.css'), cssParts.join('\n') + '\n')

writeFileSync(
  resolve(root, 'src/tokens/generated.ts'),
  `// AUTO-GENERATED by scripts/generate-tokens.ts — do not edit by hand.\n` +
    `import type { PrefectureTokens } from '../lib/colorEngine'\n\n` +
    `export interface Prefecture {\n` +
    `  id: string\n  nameJa: string\n  nameEn: string\n  region: string\n  hex: string\n  rationale: string\n  light: PrefectureTokens\n  dark: PrefectureTokens\n}\n\n` +
    `export const prefectures: Prefecture[] = ${JSON.stringify(generatedData, null, 2)}\n`,
)

const failures = allAudits.filter((a) => !a.pass)
const auditPayload = JSON.stringify(
  { total: allAudits.length, failures: failures.length, checks: allAudits },
  null,
  2,
)
mkdirSync(resolve(root, 'docs'), { recursive: true })
writeFileSync(resolve(root, 'docs/contrast-audit.json'), auditPayload)
writeFileSync(resolve(root, 'src/tokens/audit.json'), auditPayload)

console.log(`Generated tokens for ${sources.length} prefectures.`)
console.log(`Contrast audit: ${allAudits.length - failures.length}/${allAudits.length} checks passed.`)
if (failures.length > 0) {
  console.error(`FAILURES (${failures.length}):`)
  for (const f of failures) console.error(`  ${f.pair}: ${f.ratio} < ${f.min}`)
  process.exitCode = 1
}
